// 测试上传数据脚本
// 用于创建测试Excel数据，模拟上传打卡机数据

export const createTestUploadExcel = async () => {
  console.log('开始创建测试上传Excel数据...')
  
  const XLSX = await import('xlsx')
  
  // 创建测试数据（只有姓名和出勤时间两列）
  const testData = [
    { '姓名': '张组员1', '出勤时间': '15小时' },
    { '姓名': '张组员2', '出勤时间': '9小时30分钟' },
    { '姓名': '张组员3', '出勤时间': '11小时' },
    { '姓名': '李组员1', '出勤时间': '14小时' },
    { '姓名': '李组员2', '出勤时间': '10小时' },
    { '姓名': '李组员3', '出勤时间': '11小时' },
    { '姓名': '王组员1', '出勤时间': '9小时' },
    { '姓名': '王组员2', '出勤时间': '10小时' },
    { '姓名': '王组员3', '出勤时间': '9小时' },
    { '姓名': '赵组员1', '出勤时间': '8小时30分钟' },
    { '姓名': '赵组员2', '出勤时间': '10小时' },
    { '姓名': '赵组员3', '出勤时间': '11小时' },
    { '姓名': '孙组员1', '出勤时间': '9小时' },
    { '姓名': '孙组员2', '出勤时间': '10小时30分钟' },
    { '姓名': '孙组员3', '出勤时间': '11小时' }
  ]
  
  // 创建工作簿
  const wb = XLSX.utils.book_new()
  
  // 创建工作表
  const ws = XLSX.utils.json_to_sheet(testData)
  
  // 将工作表添加到工作簿
  XLSX.utils.book_append_sheet(wb, ws, '打卡数据')
  
  // 导出文件
  const fileName = `测试打卡数据_${new Date().toISOString().split('T')[0]}.xlsx`
  XLSX.writeFile(wb, fileName)
  
  console.log(`✅ 测试Excel文件已创建: ${fileName}`)
  console.log('文件包含以下数据:')
  testData.forEach((item, index) => {
    console.log(`${index + 1}. ${item['姓名']}: ${item['出勤时间']}`)
  })
  console.log('')
  console.log('请使用此文件测试上传功能')
  
  return fileName
}

